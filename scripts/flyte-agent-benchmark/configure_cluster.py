"""Write the v1 + v2 Flyte config files for the benchmark cluster, then print the
env exports and one-time auth steps.

    uv run configure_cluster.py --org <your-union-org>
    uv run configure_cluster.py --org acme --endpoint development.uniondemo.run \
        --project flytesnacks --domain development

`--org` is required: a Union endpoint needs the org/tenant for the v2 arm. The
files are written next to this script under `config/`. Auth is browser PKCE on
the first remote call — no login command; verify with `flyte whoami`.
"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG_DIR = os.path.join(HERE, "config")

V1 = """\
# Flyte v1 (flytekit / pyflyte / FlyteRemote) — benchmark cluster connection.
# Generated by configure_cluster.py. Auth: first remote call opens a browser (PKCE).
admin:
  endpoint: dns:///{endpoint}
  insecure: {insecure}
  authType: Pkce
logger:
  show-source: true
  level: 0
"""

V2 = """\
# Flyte v2 (the `flyte` SDK) — benchmark cluster connection.
# Generated by configure_cluster.py (equivalent to
#   flyte create config --endpoint {endpoint} --org {org}).
admin:
  endpoint: dns:///{endpoint}
task:
  org: {org}
  project: {project}
  domain: {domain}
image:
  builder: local
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--org", required=True, help="Union org / tenant (required for v2)")
    ap.add_argument("--endpoint", default="development.uniondemo.run",
                    help="host only, no scheme/port (default: development.uniondemo.run)")
    ap.add_argument("--project", default="flytesnacks")
    ap.add_argument("--domain", default="development")
    ap.add_argument("--insecure", action="store_true",
                    help="non-TLS endpoint (localhost/dev only)")
    a = ap.parse_args()
    endpoint = a.endpoint.replace("https://", "").replace("http://", "").rstrip("/")

    os.makedirs(CONFIG_DIR, exist_ok=True)
    v1_path = os.path.join(CONFIG_DIR, "v1.config.yaml")
    v2_path = os.path.join(CONFIG_DIR, "v2.config.yaml")
    with open(v1_path, "w") as f:
        f.write(V1.format(endpoint=endpoint, insecure=str(a.insecure).lower()))
    with open(v2_path, "w") as f:
        f.write(V2.format(endpoint=endpoint, org=a.org, project=a.project, domain=a.domain))

    print(f"wrote {v1_path}\nwrote {v2_path}\n")
    print("Run a solution on the cluster by pointing FLYTE_AGENT_BENCH_CONFIG at "
          "the arm's file\n(its presence switches the solution from local to "
          "remote); pass it inline per run:")
    print(f"  # v1 arm:\n  FLYTE_AGENT_BENCH_CONFIG={v1_path} \\\n"
          f"      FLYTECTL_CONFIG={v1_path} uv run solution.py")
    print(f"  # v2 arm:\n  FLYTE_AGENT_BENCH_CONFIG={v2_path} uv run solution.py")
    print("\nAuth (once, cached on disk — survives across runs): the first remote "
          "call opens a browser\n(PKCE). Trigger/verify up front — v2: `flyte "
          "whoami`;  v1: any `pyflyte --config <v1.yaml> run --remote ...`.")


if __name__ == "__main__":
    main()
